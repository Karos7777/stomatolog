"""Текстовые утилиты для анализа отзывов: нормализация, шинглы, лексиконы."""
import re
from typing import Iterable, Set

_WS = re.compile(r"\s+")
_NON_WORD = re.compile(r"[^0-9a-zа-яёөүң\s]", re.IGNORECASE)


def normalize(text: str) -> str:
    text = (text or "").lower().replace("ё", "е")
    text = _NON_WORD.sub(" ", text)
    return _WS.sub(" ", text).strip()


def char_shingles(text: str, k: int = 5) -> Set[str]:
    """Символьные k-граммы по нормализованному тексту (устойчивы к опечаткам и перестановке слов)."""
    t = normalize(text)
    if len(t) <= k:
        return {t} if t else set()
    return {t[i:i + k] for i in range(len(t) - k + 1)}


def jaccard(a: Set[str], b: Set[str]) -> float:
    if not a or not b:
        return 0.0
    inter = len(a & b)
    if inter == 0:
        return 0.0
    return inter / len(a | b)


def count_hits(text_norm: str, stems: Iterable[str]) -> int:
    return sum(1 for s in stems if s in text_norm)


